def tg_text(lang, key, **values):
    """Текст для Telegram на языке lang. Нет такого языка или строки — по-русски, как остальной бот."""
    template = TG_TEXTS.get(lang, TG_TEXTS["RU"]).get(key) or TG_TEXTS["RU"][key]
    return template.format(**values) if values else template
